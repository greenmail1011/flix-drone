"""輸出 Gerber（RS-274X）、Excellon 鑽孔檔、JLCPCB 的 BOM 與座標檔（CPL）。"""
import os, csv, zipfile, datetime
from shapely.geometry import Polygon, MultiPolygon
from design import *
import layout as L
import silk

NAME = 'fz-flix-carrier'
HEADER_ROT = 90   # JLC/EasyEDA 排母 0° 是橫的；這塊板子的排母是直的（沿 Y）。下單時在貼片預覽確認
OUT = os.path.join(os.path.dirname(__file__), 'fab')
GERB = os.path.join(OUT, 'gerber')
os.makedirs(GERB, exist_ok=True)

def holefree(geom):
    """在每個洞的中心畫一條垂直線把多邊形切開，切到沒有洞為止。切開的小塊邊緣完全相接，銅不會少。"""
    from shapely.geometry import MultiLineString
    from shapely.ops import split
    polys = list(geom.geoms) if hasattr(geom, 'geoms') else [geom]
    out = []
    while polys:
        p = polys.pop()
        if p.is_empty or p.geom_type != 'Polygon': continue
        p = p.simplify(0.002)
        if not p.interiors:
            out.append(p); continue
        miny, maxy = p.bounds[1] - 1, p.bounds[3] + 1
        xs = sorted({round(r.centroid.x, 4) for r in p.interiors})
        pieces = split(p, MultiLineString([[(x, miny), (x, maxy)] for x in xs]))
        polys += [q for q in pieces.geoms if q.area > 1e-6]
    return out

def c(v, axis):
    return int(round((v + OFF[axis]) * 1e6))

def xy(p):
    return f'X{c(p[0], 0)}Y{c(p[1], 1)}'

class Gerber:
    def __init__(self, function):
        self.ap, self.body, self.function = {}, [], function
        self.cur, self.pol = None, 'D'

    def aperture(self, key):
        if key not in self.ap:
            self.ap[key] = 10 + len(self.ap)
        return self.ap[key]

    def select(self, key):
        d = self.aperture(key)
        if self.cur != d:
            self.body.append(f'D{d}*'); self.cur = d

    def polarity(self, p):
        if self.pol != p:
            self.body.append(f'%LP{p}*%'); self.pol = p

    def flash(self, shp, w, h, x, y):
        self.polarity('D')
        self.select(('C', w) if shp == 'C' else ('R', w, h))
        self.body.append(f'{xy((x, y))}D03*')

    def draw(self, w, pts):
        self.polarity('D')
        self.select(('C', w))
        self.body.append(f'{xy(pts[0])}D02*')
        for p in pts[1:]: self.body.append(f'{xy(p)}D01*')

    def _ring(self, coords):
        pts = list(coords)
        out = ['G36*', f'{xy(pts[0])}D02*'] + [f'{xy(p)}D01*' for p in pts[1:]]
        if pts[0] != pts[-1]: out.append(f'{xy(pts[0])}D01*')
        out.append('G37*')
        return out

    def region(self, geom):
        """多邊形一律切成「沒有洞」的小塊再輸出（只用亮極性，不用 LPC），任何看圖軟體和廠商 CAM 都會畫得一樣。"""
        for p in holefree(geom):
            self.body += self._ring(p.exterior.coords)

    def write(self, fn):
        head = ['G04 FutureZebra Flix carrier v1.1 - generated by pcb/gerber.py*',
                f'%TF.GenerationSoftware,FutureZebra,pcb/gerber.py,1.0*%',
                f'%TF.CreationDate,{datetime.datetime.now().strftime("%Y-%m-%dT%H:%M:%S")}+08:00*%',
                f'%TF.FileFunction,{self.function}*%',
                '%FSLAX46Y46*%', '%MOMM*%', '%LPD*%', 'G01*']
        for key, d in sorted(self.ap.items(), key=lambda kv: kv[1]):
            if key[0] == 'C': head.append(f'%ADD{d}C,{key[1]:.4f}*%')
            else: head.append(f'%ADD{d}R,{key[1]:.4f}X{key[2]:.4f}*%')
        with open(os.path.join(GERB, fn), 'w', newline='\n') as f:
            f.write('\n'.join(head + self.body + ['M02*']) + '\n')

def copper(layer, fn, func):
    g = Gerber(func)
    feats = [f for f in L.FEATS if f.layer == layer]
    for f in feats:                                     # 先畫鋪銅
        if f.kind == 'region' and f.net == 'GND': g.region(f.gerber[1])
    for f in feats:
        if f.kind == 'region' and f.net == 'GND': continue
        t = f.gerber
        if t[0] == 'flash': g.flash(*t[1:])
        elif t[0] == 'draw': g.draw(t[1], t[2])
        else: g.region(t[1])
    g.write(fn)

def mask(layer, fn, func):
    g = Gerber(func)
    for f in L.FEATS:
        if f.layer == layer and f.kind in ('tht', 'smd'):
            _, shp, w, h, x, y = f.gerber
            g.flash(shp, w + 0.1, h + 0.1, x, y)
    for x, y in MOUNT_HOLES: g.flash('C', MOUNT_D + 0.2, MOUNT_D + 0.2, x, y)
    g.write(fn)

def paste(fn):
    g = Gerber('Paste,Top')
    for ref, p, x, y, w, h in L.SMD: g.flash('R', w, h, x, y)
    g.write(fn)

def silkscreen(layer, fn, func):
    g = Gerber(func)
    g.region(silk.clipped(layer))
    g.write(fn)

def outline(fn):
    g = Gerber('Profile,NP')
    pts = list(BOARD.exterior.coords)
    g.draw(0.1, pts)
    g.write(fn)

def drill(fn, plated):
    holes = [(x, y, d) for x, y, d, pl, net in L.DRILLS if pl] if plated else [(x, y, MOUNT_D) for x, y in MOUNT_HOLES]
    sizes = sorted({d for *_, d in holes})
    lines = ['M48', f'; DRILL file FutureZebra Flix carrier v1.1 ({"PTH" if plated else "NPTH"})',
             '; FORMAT={-:-/ absolute / metric / decimal}',
             f'; #@! TF.FileFunction,{"Plated" if plated else "NonPlated"},1,2,{"PTH" if plated else "NPTH"}',
             'FMAT,2', 'METRIC']
    for i, d in enumerate(sizes, 1): lines.append(f'T{i}C{d:.3f}')
    lines += ['%', 'G90', 'G05']
    for i, d in enumerate(sizes, 1):
        lines.append(f'T{i}')
        for x, y, dd in holes:
            if dd == d: lines.append(f'X{x + OFF[0]:.3f}Y{y + OFF[1]:.3f}')
    lines += ['T0', 'M30']
    with open(os.path.join(GERB, fn), 'w', newline='\n') as f: f.write('\n'.join(lines) + '\n')
    return {d: sum(1 for *_, dd in holes if dd == d) for d in sizes}

def bom_cpl():
    with open(os.path.join(OUT, f'{NAME}-BOM.csv'), 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['Comment', 'Designator', 'Footprint', 'LCSC Part #'])
        w.writerow(['AO3400A', ','.join(f'Q{M["m"]}' for M in MOTORS), 'SOT-23', 'C20917'])
        w.writerow(['10k', ','.join(f'R{M["m"]}' for M in MOTORS), '0603', 'C25804'])
        w.writerow(['1x10P female header 2.54mm H8.5', 'H1,H2,H3,H4', 'Plugin,P=2.54mm 1x10P', 'C2905418'])
    with open(os.path.join(OUT, f'{NAME}-CPL.csv'), 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['Designator', 'Mid X', 'Mid Y', 'Layer', 'Rotation'])
        for M in MOTORS:
            qx, qy = M['q']; rx, ry = M['r']
            w.writerow([f'Q{M["m"]}', f'{qx + OFF[0]:.3f}mm', f'{qy + OFF[1]:.3f}mm', 'Top', M['rot']])
        for M in MOTORS:
            rx, ry = M['r']
            w.writerow([f'R{M["m"]}', f'{rx + OFF[0]:.3f}mm', f'{ry + OFF[1]:.3f}mm', 'Top', 0])
        # MINI32 排母：每排 10 孔的中心（y = 11.43 - 4.5 × 2.54 = 0）。排母左右對稱，只要長邊沿 Y（前後）方向即可
        for i, col in enumerate(('LO', 'LI', 'RI', 'RO'), 1):
            w.writerow([f'H{i}', f'{COLS[col] + OFF[0]:.3f}mm', f'{0 + OFF[1]:.3f}mm', 'Top', HEADER_ROT])

FILES = {
    'F_Cu.gtl': lambda fn: copper('F', fn, 'Copper,L1,Top'),
    'B_Cu.gbl': lambda fn: copper('B', fn, 'Copper,L2,Bot'),
    'F_Mask.gts': lambda fn: mask('F', fn, 'Soldermask,Top'),
    'B_Mask.gbs': lambda fn: mask('B', fn, 'Soldermask,Bot'),
    'F_Silkscreen.gto': lambda fn: silkscreen('F', fn, 'Legend,Top'),
    'B_Silkscreen.gbo': lambda fn: silkscreen('B', fn, 'Legend,Bot'),
    'F_Paste.gtp': paste,
    'Edge_Cuts.gm1': outline,
}

def main():
    for fn in os.listdir(GERB): os.remove(os.path.join(GERB, fn))
    for suffix, fun in FILES.items(): fun(f'{NAME}-{suffix}')
    pth = drill(f'{NAME}-PTH.drl', True)
    npth = drill(f'{NAME}-NPTH.drl', False)
    bom_cpl()
    z = os.path.join(OUT, f'{NAME}-gerber.zip')
    with zipfile.ZipFile(z, 'w', zipfile.ZIP_DEFLATED) as zf:
        for fn in sorted(os.listdir(GERB)): zf.write(os.path.join(GERB, fn), fn)
    print('PTH', pth, 'NPTH', npth)
    print('zip', z)

if __name__ == '__main__':
    main()
