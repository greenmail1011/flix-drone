"""輸出 JLCPCB 生產檔：Gerber（RS-274X）、Excellon 鑽孔（含長圓孔）、BOM、CPL。

板子外圍加一圈 12 mm 寬的工藝邊（JLC 標準貼片單片至少 70 × 70 mm），
用 4 個郵票孔連接點和板子相連，收到後折斷。工藝邊上有 3 個光學定位點和 4 個定位孔。
"""
import os, csv, zipfile, datetime, math, pickle, sys
from shapely.geometry import Point, Polygon, box, LineString, MultiPolygon
from shapely.ops import unary_union
from shapely import affinity
import board as B
from route import pad_geom
import silk

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'fab')
GERB = os.path.join(OUT, 'gerber')
NAME = B.NAME

# ---------------- 工藝邊 ----------------
FRAME = (-35.0, -38.25, 35.0, 31.75)          # 70 × 70 mm
OFF = (-FRAME[0], -FRAME[1])                    # 輸出時平移，讓工藝邊左下角 = (0, 0)
GAP = 2.0                                       # 板子與工藝邊之間銑空的寬度
TABS = [((-8.0, 19.5), 'N'), ((8.0, 19.5), 'N'), ((-15.5, -19.5), 'S'), ((15.5, -19.5), 'S')]
TAB_W = 4.0
BITE_D, BITE_PITCH, BITE_N = 0.5, 0.8, 5
FIDUCIALS = [(-30.0, 27.5), (30.0, 27.5), (-30.0, -34.0)]   # 不對稱，機器才分得出方向
FID_CU, FID_MASK = 1.0, 2.0
TOOLING = [(-33.0, 29.75), (33.0, 29.75), (-33.0, -36.25), (33.0, -36.25)]
TOOLING_D = 1.152


def material():
    outer = box(*FRAME)
    cut = B.BOARD.buffer(GAP, join_style=2)
    frame = outer.difference(cut)
    tabs = []
    for (x, y), side in TABS:
        dy = GAP + 0.5
        tabs.append(box(x - TAB_W / 2, y - 0.5 if side == 'N' else y - dy, x + TAB_W / 2, y + dy if side == 'N' else y + 0.5))
    return unary_union([frame, B.BOARD] + tabs)


def mouse_bites():
    holes = []
    for (x, y), side in TABS:
        yy = y + (BITE_D / 2 + 0.05) * (1 if side == 'N' else -1)   # 孔心在板邊外一點，折斷後毛邊在工藝邊那側
        for k in range(BITE_N):
            holes.append((x + (k - (BITE_N - 1) / 2) * BITE_PITCH, yy))
    return holes


# ---------------- Gerber ----------------
def c(v, axis):
    return int(round((v + OFF[axis]) * 1e6))


def xy(p):
    return f'X{c(p[0], 0)}Y{c(p[1], 1)}'


def holefree(geom):
    from shapely.geometry import MultiLineString
    from shapely.ops import split
    polys = list(geom.geoms) if hasattr(geom, 'geoms') else [geom]
    out = []
    while polys:
        p = polys.pop()
        if p.is_empty or p.geom_type != 'Polygon': continue
        p = p.simplify(0.002)
        if not p.interiors:
            out.append(p); continue
        miny, maxy = p.bounds[1] - 1, p.bounds[3] + 1
        xs = sorted({round(r.centroid.x, 4) for r in p.interiors})
        pieces = split(p, MultiLineString([[(x, miny), (x, maxy)] for x in xs]))
        polys += [q for q in pieces.geoms if q.area > 1e-7]
    return out


class Gerber:
    def __init__(self, function):
        self.ap, self.body, self.function = {}, [], function
        self.cur = None

    def aperture(self, key):
        if key not in self.ap: self.ap[key] = 10 + len(self.ap)
        return self.ap[key]

    def select(self, key):
        d = self.aperture(key)
        if self.cur != d:
            self.body.append(f'D{d}*'); self.cur = d

    def flash(self, key, x, y):
        self.select(key)
        self.body.append(f'{xy((x, y))}D03*')

    def draw(self, w, pts):
        self.select(('C', round(w, 4)))
        self.body.append(f'{xy(pts[0])}D02*')
        for p in pts[1:]: self.body.append(f'{xy(p)}D01*')

    def region(self, geom):
        for p in holefree(geom):
            pts = list(p.exterior.coords)
            self.body += ['G36*', f'{xy(pts[0])}D02*'] + [f'{xy(q)}D01*' for q in pts[1:]] + ['G37*']

    def write(self, fn):
        head = [f'G04 FutureZebra Flix onboard {B.VERSION} - generated by pcb2/export.py*',
                '%TF.GenerationSoftware,FutureZebra,pcb2/export.py,2.0*%',
                f'%TF.CreationDate,{datetime.datetime.now().strftime("%Y-%m-%dT%H:%M:%S")}+08:00*%',
                f'%TF.FileFunction,{self.function}*%', '%FSLAX46Y46*%', '%MOMM*%', '%LPD*%', 'G01*']
        for key, d in sorted(self.ap.items(), key=lambda kv: kv[1]):
            if key[0] == 'C': head.append(f'%ADD{d}C,{key[1]:.4f}*%')
            elif key[0] == 'R': head.append(f'%ADD{d}R,{key[1]:.4f}X{key[2]:.4f}*%')
            elif key[0] == 'O': head.append(f'%ADD{d}O,{key[1]:.4f}X{key[2]:.4f}*%')
        with open(os.path.join(GERB, fn), 'w', newline='\n') as f:
            f.write('\n'.join(head + self.body + ['M02*']) + '\n')


def pad_flash(g, p, grow=0.0):
    """用標準光圈畫焊墊（0/90/180/270 度）；其他角度用多邊形。"""
    r = round(p.rot) % 180
    w, h = (p.w, p.h) if r == 0 else (p.h, p.w)
    if p.shape == 'circle':
        g.flash(('C', round(p.w + 2 * grow, 4)), p.x, p.y)
    elif r in (0, 90):
        k = 'O' if p.shape == 'oval' else 'R'
        g.flash((k, round(w + 2 * grow, 4), round(h + 2 * grow, 4)), p.x, p.y)
    else:
        g.region(pad_geom(p).buffer(grow, join_style=2))


def copper(R, layer, fn, func):
    g = Gerber(func)
    for f in R.feats:                       # 鋪銅先畫
        if f.layer == layer and f.kind == 'region': g.region(f.geom)
    for f in R.feats:
        if f.layer != layer or f.kind == 'region': continue
        t = f.gerber
        if t[0] == 'pad': pad_flash(g, t[1])
        elif t[0] == 'via': g.flash(('C', 0.6), t[1], t[2])
        elif t[0] == 'draw':
            if len(t[2]) == 1: g.flash(('C', round(t[1], 4)), *t[2][0])
            else: g.draw(t[1], t[2])
    if layer == 'F':
        for x, y in FIDUCIALS: g.flash(('C', FID_CU), x, y)
    g.write(fn)


MASK_GROW = 0.05


def mask(R, layer, fn, func):
    g = Gerber(func)
    for f in R.feats:
        if f.layer == layer and f.kind in ('smd', 'tht'):
            pad_flash(g, f.gerber[1], MASK_GROW)
    for x, y in B.MOUNT_HOLES: g.flash(('C', B.MOUNT_D + 0.2), x, y)
    for x, y, dw, dh, pl, n in R.drills:
        if not pl: g.flash(('C', round(max(dw, dh) + 0.2, 4)), x, y)
    for x, y in FIDUCIALS:
        if layer == 'F': g.flash(('C', FID_MASK), x, y)
    for x, y in TOOLING: g.flash(('C', TOOLING_D + 0.2), x, y)
    g.write(fn)


def paste(R, fn):
    g = Gerber('Paste,Top')
    for f in R.feats:
        if f.layer == 'F' and f.kind == 'smd':
            p = f.gerber[1]
            if p.ref == 'U1' and p.name == '39':
                # 模組底部大焊墊：開 4 個小窗（約 40% 面積），避免模組浮起
                for dx in (-1.3, 1.3):
                    for dy in (-1.3, 1.3):
                        g.flash(('R', 1.6, 1.6), p.x + dx, p.y + dy)
                continue
            pad_flash(g, p)
    g.write(fn)


def silkscreen(R, layer, fn, func):
    g = Gerber(func)
    g.region(silk.clipped(R, layer, material()))
    g.write(fn)


def outline(fn):
    g = Gerber('Profile,NP')
    m = material()
    polys = list(m.geoms) if hasattr(m, 'geoms') else [m]
    for p in polys:
        g.draw(0.1, list(p.exterior.coords))
        for r in p.interiors: g.draw(0.1, list(r.coords))
    g.write(fn)


def drill(R, fn, plated):
    rnd, slots = [], []
    if plated:
        for x, y, dw, dh, pl, n in R.drills:
            if not pl: continue
            if abs(dw - dh) < 1e-6: rnd.append((x, y, dw))
            else: slots.append((x, y, dw, dh))
    else:
        rnd += [(x, y, B.MOUNT_D) for x, y in B.MOUNT_HOLES]
        rnd += [(x, y, dw) for x, y, dw, dh, pl, n in R.drills if not pl]
        rnd += [(x, y, TOOLING_D) for x, y in TOOLING]
        rnd += [(x, y, BITE_D) for x, y in mouse_bites()]
    sizes = sorted({round(d, 3) for *_, d in rnd} | {round(min(s[2], s[3]), 3) for s in slots})
    lines = ['M48', f'; DRILL file FutureZebra Flix onboard {B.VERSION} ({"PTH" if plated else "NPTH"})',
             '; FORMAT={-:-/ absolute / metric / decimal}',
             f'; #@! TF.FileFunction,{"Plated" if plated else "NonPlated"},1,2,{"PTH" if plated else "NPTH"}', 'FMAT,2', 'METRIC']
    for i, d in enumerate(sizes, 1): lines.append(f'T{i}C{d:.3f}')
    lines += ['%', 'G90', 'G05']
    for i, d in enumerate(sizes, 1):
        lines.append(f'T{i}')
        for x, y, dd in rnd:
            if round(dd, 3) == d: lines.append(f'X{x + OFF[0]:.3f}Y{y + OFF[1]:.3f}')
        for x, y, dw, dh in slots:
            if round(min(dw, dh), 3) != d: continue
            pad = min((p for p in B.PADS if p.drill and p.kind == 'tht'), key=lambda p: math.hypot(p.x - x, p.y - y))
            L = (max(dw, dh) - min(dw, dh)) / 2
            ang = math.radians(pad.rot + (90 if dh > dw else 0))
            x0, y0 = x - L * math.cos(ang) + OFF[0], y - L * math.sin(ang) + OFF[1]
            x1, y1 = x + L * math.cos(ang) + OFF[0], y + L * math.sin(ang) + OFF[1]
            lines.append(f'X{x0:.3f}Y{y0:.3f}G85X{x1:.3f}Y{y1:.3f}')
    lines += ['T0', 'M30']
    with open(os.path.join(GERB, fn), 'w', newline='\n') as f: f.write('\n'.join(lines) + '\n')
    return {d: sum(1 for *_, dd in rnd if round(dd, 3) == d) for d in sizes}, len(slots)


# ---------------- BOM / CPL ----------------
def body_center(cmp):
    """JLC 座標檔用元件本體中心（由 KiCad 封裝的 F.Fab 外框算）。"""
    f = B.fpobj(cmp['fp'])
    pts = [p for seg in f.fab for p in seg]
    if not pts: return cmp['x'], cmp['y']
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    a = math.radians(cmp['rot'])
    return cmp['x'] + cx * math.cos(a) - cy * math.sin(a), cmp['y'] + cx * math.sin(a) + cy * math.cos(a)


def bom_cpl():
    groups = {}
    for cmp in B.COMPS:
        groups.setdefault(cmp['part'], []).append(cmp['ref'])
    def key(r):
        import re
        m = re.match(r'([A-Z]+)(\d+)', r); return (m.group(1), int(m.group(2)))
    with open(os.path.join(OUT, f'{NAME}-BOM.csv'), 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        w.writerow(['Comment', 'Designator', 'Footprint', 'LCSC Part #'])
        for part, refs in sorted(groups.items(), key=lambda kv: key(sorted(kv[1], key=key)[0])):
            val, lcsc, pkg = B.PARTS[part]
            w.writerow([val, ','.join(sorted(refs, key=key)), pkg, lcsc])
    with open(os.path.join(OUT, f'{NAME}-CPL.csv'), 'w', newline='', encoding='utf-8') as f:
        w = csv.writer(f)
        w.writerow(['Designator', 'Mid X', 'Mid Y', 'Layer', 'Rotation'])
        for cmp in sorted(B.COMPS, key=lambda c: key(c['ref'])):
            x, y = body_center(cmp)
            w.writerow([cmp['ref'], f'{x + OFF[0]:.3f}mm', f'{y + OFF[1]:.3f}mm', 'Top', int(cmp['rot']) % 360])
    return groups


FILES = {
    'F_Cu.gtl': lambda R, fn: copper(R, 'F', fn, 'Copper,L1,Top'),
    'B_Cu.gbl': lambda R, fn: copper(R, 'B', fn, 'Copper,L2,Bot'),
    'F_Mask.gts': lambda R, fn: mask(R, 'F', fn, 'Soldermask,Top'),
    'B_Mask.gbs': lambda R, fn: mask(R, 'B', fn, 'Soldermask,Bot'),
    'F_Silkscreen.gto': lambda R, fn: silkscreen(R, 'F', fn, 'Legend,Top'),
    'B_Silkscreen.gbo': lambda R, fn: silkscreen(R, 'B', fn, 'Legend,Bot'),
    'F_Paste.gtp': paste,
    'Edge_Cuts.gm1': lambda R, fn: outline(fn),
}


def main(pk='/tmp/final.pkl'):
    R = pickle.load(open(pk, 'rb'))
    os.makedirs(GERB, exist_ok=True)
    for fn in os.listdir(GERB): os.remove(os.path.join(GERB, fn))
    for suffix, fun in FILES.items(): fun(R, f'{NAME}-{suffix}')
    pth = drill(R, f'{NAME}-PTH.drl', True)
    npth = drill(R, f'{NAME}-NPTH.drl', False)
    groups = bom_cpl()
    z = os.path.join(OUT, f'{NAME}-gerber.zip')
    with zipfile.ZipFile(z, 'w', zipfile.ZIP_DEFLATED) as zf:
        for fn in sorted(os.listdir(GERB)): zf.write(os.path.join(GERB, fn), fn)
    print('PTH', pth, 'NPTH', npth)
    print('BOM', len(groups), '種料件', len(B.COMPS), '個元件')
    print('zip', z)


if __name__ == '__main__':
    main(*sys.argv[1:])
